"""The audit-summary vocabulary: everything an audit summary may say.

An audit summary records that the owner approved one model-proposed action
and that Maria authorised that attempt for dispatch. Brain writes it, the
memory layer stores it, and the audit tool shows it, and this module is the
one place all three take its words from. Every field is generated by Maria
and drawn from a closed vocabulary: her own UTC timestamp, the canonical
contract identifier of an action a model may propose, the owner's decision, a
generalised target class, and, appended after dispatch, the outcome the
tool's success flag reported. There is deliberately no field for the request,
the proposal, an argument, a fingerprint, private context, a root's name, a
host path, a tool's result, or an exception's text, so none of them can be
stored by accident.

A summary means an approved execution attempt was authorised for dispatch. By
itself it does not prove the tool ran: the outcome is a separate value, and a
summary without one means nothing is known about what happened.

Validation is strict and runs in both directions. The memory layer checks
every value before writing it and again after reading it, and a value outside
this vocabulary is refused with one fixed message that repeats nothing. This
module reads nothing, stores nothing, and logs nothing.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import datetime, timezone
from enum import Enum
from types import MappingProxyType

from core.action_contracts import ActionContract, RootClass


# The actions an audit summary may name: exactly the actions a reasoning model
# may propose. They are declared again here rather than imported, so what a
# stored summary may say is its own declaration, and a test holds it to the
# compiler's allowlist.
AUDITED_ACTIONS = frozenset(
    {
        "calculator.calculate",
        "filesystem.list",
        "system.current_time",
        "tasks.create",
        "reminders.create",
    }
)

# How many summaries the audit listing shows, and the one more it reads to
# learn whether more exist without counting them.
AUDIT_LIST_LIMIT = 20
AUDIT_QUERY_LIMIT = AUDIT_LIST_LIMIT + 1

# Maria's one timestamp form for a summary: UTC to the second with a literal
# Z, always exactly this long, so every stored timestamp reads alike.
AUDIT_TIMESTAMP_FORMAT = "%Y-%m-%dT%H:%M:%SZ"
_AUDIT_TIMESTAMP_PATTERN = re.compile(
    r"[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z"
)

AUDIT_SUMMARY_MESSAGE = (
    "An audit summary may hold only values from Maria's audit vocabulary."
)
AUDIT_SUMMARY_ID_MESSAGE = "Audit summary id must be a positive whole number."


class AuditDecision(str, Enum):
    """What authorised an audited execution attempt."""

    OWNER_APPROVED = "owner_approved"


class AuditTarget(str, Enum):
    """The generalised class of what an audited action acted on.

    A path's text, its root's name, and its host location are never stored;
    an action whose contract declares a path argument is recorded only as
    acting inside a named filesystem root.
    """

    NONE = "none"
    NAMED_FILESYSTEM_ROOT = "named_filesystem_root"


class AuditOutcome(str, Enum):
    """What the tool's own success flag reported after dispatch."""

    SUCCEEDED = "succeeded"
    FAILED = "failed"


# Every path root class a contract can declare, and the target it is audited
# as. A root class missing here has no audited target, so an action using it
# cannot be audited, and therefore cannot run as a model-proposed action.
_TARGETS_BY_ROOT_CLASS = MappingProxyType(
    {RootClass.NAMED_FILESYSTEM_ROOT: AuditTarget.NAMED_FILESYSTEM_ROOT}
)


@dataclass(frozen=True)
class AuditSummary:
    """One stored audit summary with its outcome, every field validated.

    ``outcome`` is None when no outcome was ever recorded, which means the
    execution is unknown: Maria may have stopped after authorising the
    attempt, during the tool's run, or before the outcome could be written.
    """

    summary_id: int
    created_at: str
    action: str
    decision: AuditDecision
    target: AuditTarget
    outcome: AuditOutcome | None = None

    def __post_init__(self) -> None:
        """Refuse any field outside the audit vocabulary."""
        if not (
            is_audit_summary_id(self.summary_id)
            and is_audit_timestamp(self.created_at)
            and is_audited_action(self.action)
            and type(self.decision) is AuditDecision
            and type(self.target) is AuditTarget
            and (self.outcome is None or type(self.outcome) is AuditOutcome)
        ):
            raise ValueError(AUDIT_SUMMARY_MESSAGE)

    @classmethod
    def from_stored(
        cls,
        summary_id: object,
        created_at: object,
        action: object,
        decision: object,
        target: object,
        outcome: object,
    ) -> AuditSummary:
        """Build a summary from stored values, refusing any it cannot hold.

        Each enumerated value must be exact text spelling one member, and an
        absent outcome must be exactly None. Anything else raises
        ``ValueError`` with the fixed message, which names no value.
        """
        return cls(
            summary_id,
            created_at,
            action,
            _stored_member(AuditDecision, decision),
            _stored_member(AuditTarget, target),
            None if outcome is None else _stored_member(AuditOutcome, outcome),
        )


def audit_timestamp() -> str:
    """Return the current UTC time in Maria's audit timestamp form."""
    return datetime.now(timezone.utc).strftime(AUDIT_TIMESTAMP_FORMAT)


def is_audit_timestamp(value: object) -> bool:
    """Return whether a value is exactly one valid audit timestamp.

    It must be exact text in the one form ``audit_timestamp`` writes, with
    every field at its fixed width, and it must name a real calendar second.
    The fixed-width pattern settles the form and parsing settles the
    calendar, so the answer is the same on every platform.
    """
    if type(value) is not str or not _AUDIT_TIMESTAMP_PATTERN.fullmatch(value):
        return False
    try:
        datetime.strptime(value, AUDIT_TIMESTAMP_FORMAT)
    except ValueError:
        return False
    return True


def is_audited_action(value: object) -> bool:
    """Return whether a value is exactly an action a summary may name."""
    return type(value) is str and value in AUDITED_ACTIONS


def is_audit_summary_id(value: object) -> bool:
    """Return whether a value is an exact positive int, never a bool."""
    return type(value) is int and value >= 1


def audit_target(contract: ActionContract) -> AuditTarget:
    """Return the generalised target class one contract's action acts on.

    It is decided from the contract alone, never from an argument value: an
    action declaring any path argument acts inside a named filesystem root,
    whether or not a path was supplied, and any other action has no target.
    A path argument of a root class with no audited target raises
    ``ValueError``, so such an action can never be audited, or run.
    """
    targets = set()
    for argument in contract.arguments:
        if argument.root_class is None:
            continue
        target = _TARGETS_BY_ROOT_CLASS.get(argument.root_class)
        if target is None:
            raise ValueError(AUDIT_SUMMARY_MESSAGE)
        targets.add(target)
    if not targets:
        return AuditTarget.NONE
    if len(targets) != 1:
        raise ValueError(AUDIT_SUMMARY_MESSAGE)
    return targets.pop()


def _stored_member(enum_type: type[Enum], value: object) -> Enum:
    """Return the member a stored value spells exactly, or refuse it.

    The value is compared only after its exact type is settled, so neither
    a str subclass nor a look-alike object can stand in for a member.
    """
    if type(value) is str:
        for member in enum_type:
            if member.value == value:
                return member
    raise ValueError(AUDIT_SUMMARY_MESSAGE)
